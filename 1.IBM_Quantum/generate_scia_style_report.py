"""
Run the QAOA error-localization pipeline over every record in testdata.csv
and produce two summary tables in the same style as CONCORD/SCIA's own
output, for direct comparison:

  1. STATISTICS OF IMPUTED VARIABLES (matches STATIS.Example_Tunisia)
  2. LIST OF IMPUTATIONS PER RECORD  (matches LISTAIMP.Example_Tunisia)

Both are now computed using the FULL Fellegi-Holt edit closure (explicit
REGOLE.txt lines + implied edits generated by resolution -- see
generate_implied_edits.py), not just the 10 explicit lines. This was
verified necessary and sufficient to match CONCORD's own minimum-change
answers exactly on records R2 and R4, where hitting only the originally
active explicit edits produced an incomplete (inconsistent) correction.

Requires: qiskit, qiskit-aer, scipy, numpy (same as ibm_qaoa_solver.py)
Usage:    python generate_scia_style_report.py [--hardware] [--reps 3]
"""

import argparse
from collections import defaultdict, Counter

import ibm_qaoa_solver as solver


def run_report(reps=3, hardware=False, backend_name=None,
               sim_shots=4096, hardware_shots=8192):
    all_variables, cost = solver.load_variables()
    rules_logic = solver.load_rules_logic()
    records = solver.load_all_records()
    closure = solver.get_closure(rules_logic, all_variables)

    per_var_times = defaultdict(int)
    per_var_edits = defaultdict(Counter)
    per_record = []  # for the LISTAIMP-style table, in record order
    n_processed = len(records)
    n_with_errors = 0

    for record in records:
        result = solver.localize_record(
            record, all_variables, cost, rules_logic,
            reps=reps, hardware=hardware, backend_name=backend_name,
            sim_shots=sim_shots, hardware_shots=hardware_shots, verbose=True,
            closure=closure,
        )
        if result is None:
            continue
        n_with_errors += 1
        per_record.append({
            "record_id": record["record_id"],
            "corrections": result["corrections"],
        })
        for v in result["corrections"]:
            per_var_times[v] += 1
            for a in result["violated"]:
                if v in a["variables"]:
                    per_var_edits[v][a["regole_line"]] += 1

    return (all_variables, per_var_times, per_var_edits, per_record,
            n_processed, n_with_errors)


def format_stats_table(all_variables, per_var_times, per_var_edits, n_with_errors):
    """Percentages are relative to the number of records that needed at
    least one correction (n_with_errors), matching CONCORD/SCIA's own
    convention -- NOT the total number of records processed."""
    lines = []
    lines.append("STATISTICS OF IMPUTED VARIABLES WITH VIOLATED EDITS (QAOA)")
    header = f"{'name':<8}{'times':>7}{'%':>8}  " + "  ".join(
        f"{'edit':>4}{'times':>7}" for _ in range(4))
    lines.append(header)

    for v in all_variables:
        times = per_var_times.get(v, 0)
        if times == 0:
            continue
        pct = 100.0 * times / n_with_errors
        edits = sorted(per_var_edits[v].items(), key=lambda kv: str(kv[0]))
        cells = []
        for i in range(4):
            if i < len(edits):
                edit_num, edit_count = edits[i]
            else:
                edit_num, edit_count = 0, 0
            cells.append(f"{edit_num:>4}{edit_count:>7}")
        lines.append(f"{v:<8}{times:>7}{pct:>8.2f}  " + "  ".join(cells))

    lines.append("edit 0 = padding (fewer than 4 distinct edits for this variable)")
    lines.append("edit labels 1-10 are explicit REGOLE.txt lines; labels starting")
    lines.append("with 'I' (e.g. I3) are implied edits generated by resolution --")
    lines.append("see generate_implied_edits.py and rules_logic.csv.")
    return "\n".join(lines)


def format_listaimp_table(per_record):
    """Mirrors LISTAIMP.Example_Tunisia: one row per corrected record,
    numbered among the records that needed correction, listing which
    fields were changed."""
    lines = []
    lines.append("LIST OF IMPUTATIONS PER RECORD (QAOA)")
    lines.append(f"{'N_ERRATO':<10}{'IMPUTAZIONE':<13}{'N_VARIABILI':<13}VARIABILI")
    for i, r in enumerate(per_record, 1):
        n = len(r["corrections"])
        vars_str = " ".join(r["corrections"])
        lines.append(f"{i:<10}{'R':<13}{n:<13}{vars_str}")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--reps", type=int, default=3)
    parser.add_argument("--hardware", action="store_true")
    parser.add_argument("--backend", default=None)
    parser.add_argument("--sim-shots", type=int, default=4096)
    parser.add_argument("--hardware-shots", type=int, default=8192)
    parser.add_argument("--out", default="qaoa_statis_report.txt")
    parser.add_argument("--out-listaimp", default="qaoa_listaimp_report.txt")
    args = parser.parse_args()

    if args.hardware:
        print("NOTE: --hardware submits ONE confirmatory job per record "
              "that has at least one violated rule (parameters are always "
              "optimized on the simulator first).\n")

    (all_variables, per_var_times, per_var_edits, per_record,
     n_processed, n_with_errors) = run_report(
        reps=args.reps, hardware=args.hardware, backend_name=args.backend,
        sim_shots=args.sim_shots, hardware_shots=args.hardware_shots)

    stats_report = format_stats_table(all_variables, per_var_times,
                                       per_var_edits, n_with_errors)
    listaimp_report = format_listaimp_table(per_record)

    header = (f"Processed {n_processed} records, {n_with_errors} needed at "
              f"least one correction (percentages relative to {n_with_errors}).")

    print(f"\n{header}\n")
    print(stats_report)
    print()
    print(listaimp_report)

    with open(args.out, "w") as f:
        f.write(header + "\n\n")
        f.write(stats_report + "\n")

    with open(args.out_listaimp, "w") as f:
        f.write(header + "\n\n")
        f.write(listaimp_report + "\n")

    print(f"\nReports written to {args.out} and {args.out_listaimp}")


if __name__ == "__main__":
    main()
