"""
Run the D-Wave error-localization pipeline over every record in
testdata.csv and produce the same two summary tables as
generate_scia_style_report.py (IBM/QAOA version), for direct comparison
with CONCORD/SCIA and with the QAOA results.

Requires: dwave-ocean-sdk
Usage:    python generate_dwave_report.py [--sampler sim|hybrid|qpu]
"""

import argparse
from collections import defaultdict, Counter

import dwave_solver as dw
import ibm_qaoa_solver as solver


def run_report(sampler_kind="sim", backend_name=None, num_reads=200):
    all_variables, cost = solver.load_variables()
    rules_logic = solver.load_rules_logic()
    records = solver.load_all_records()
    closure = solver.get_closure(rules_logic, all_variables)

    per_var_times = defaultdict(int)
    per_var_edits = defaultdict(Counter)
    per_record = []
    n_processed = len(records)
    n_with_errors = 0

    for record in records:
        result = dw.localize_record(
            record, all_variables, cost, rules_logic, closure=closure,
            sampler_kind=sampler_kind, backend_name=backend_name,
            num_reads=num_reads, verbose=True,
        )
        if result is None:
            continue
        n_with_errors += 1
        per_record.append({
            "record_id": record["record_id"],
            "corrections": result["corrections"],
        })
        for v in result["corrections"]:
            per_var_times[v] += 1
            for a in result["violated"]:
                if v in a["variables"]:
                    per_var_edits[v][a["regole_line"] if "regole_line" in a
                                       else a["rule_id"]] += 1

    return (all_variables, per_var_times, per_var_edits, per_record,
            n_processed, n_with_errors)


def format_stats_table(all_variables, per_var_times, per_var_edits, n_with_errors):
    lines = []
    lines.append("STATISTICS OF IMPUTED VARIABLES WITH VIOLATED EDITS (D-WAVE)")
    header = f"{'name':<8}{'times':>7}{'%':>8}  " + "  ".join(
        f"{'edit':>4}{'times':>7}" for _ in range(4))
    lines.append(header)
    for v in all_variables:
        times = per_var_times.get(v, 0)
        if times == 0:
            continue
        pct = 100.0 * times / n_with_errors
        edits = sorted(per_var_edits[v].items(), key=lambda kv: str(kv[0]))
        cells = []
        for i in range(4):
            edit_num, edit_count = edits[i] if i < len(edits) else (0, 0)
            cells.append(f"{edit_num:>4}{edit_count:>7}")
        lines.append(f"{v:<8}{times:>7}{pct:>8.2f}  " + "  ".join(cells))
    lines.append("edit 0 = padding (fewer than 4 distinct edits for this variable)")
    lines.append("edit labels 1-10 are explicit REGOLE.txt lines; labels starting")
    lines.append("with 'I' are implied edits generated by resolution.")
    return "\n".join(lines)


def format_listaimp_table(per_record):
    lines = []
    lines.append("LIST OF IMPUTATIONS PER RECORD (D-WAVE)")
    lines.append(f"{'N_ERRATO':<10}{'IMPUTAZIONE':<13}{'N_VARIABILI':<13}VARIABILI")
    for i, r in enumerate(per_record, 1):
        n = len(r["corrections"])
        vars_str = " ".join(r["corrections"])
        lines.append(f"{i:<10}{'R':<13}{n:<13}{vars_str}")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--sampler", choices=["sim", "hybrid", "qpu"], default="sim")
    parser.add_argument("--backend", default=None)
    parser.add_argument("--num-reads", type=int, default=200)
    parser.add_argument("--out", default="dwave_statis_report.txt")
    parser.add_argument("--out-listaimp", default="dwave_listaimp_report.txt")
    args = parser.parse_args()

    (all_variables, per_var_times, per_var_edits, per_record,
     n_processed, n_with_errors) = run_report(
        sampler_kind=args.sampler, backend_name=args.backend,
        num_reads=args.num_reads)

    stats_report = format_stats_table(all_variables, per_var_times,
                                       per_var_edits, n_with_errors)
    listaimp_report = format_listaimp_table(per_record)
    header = (f"Processed {n_processed} records, {n_with_errors} needed at "
              f"least one correction (percentages relative to {n_with_errors}). "
              f"Sampler: {args.sampler}.")

    print(f"\n{header}\n")
    print(stats_report)
    print()
    print(listaimp_report)

    with open(args.out, "w") as f:
        f.write(header + "\n\n" + stats_report + "\n")
    with open(args.out_listaimp, "w") as f:
        f.write(header + "\n\n" + listaimp_report + "\n")

    print(f"\nReports written to {args.out} and {args.out_listaimp}")


if __name__ == "__main__":
    main()
